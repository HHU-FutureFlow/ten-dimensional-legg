/* ===== 分带选择: 实测腿长 -> K 组, 1cm 迟滞防抖 =====
 * 带 k 中心 = 0.15 + 0.05k, 相邻带边界 = 0.175 + 0.05k。
 * 上电默认 0.30 带; 恢复流程从低腿长(折叠≈0.11)起步时, 首几次调用会逐带降到 l015。 */
static float (*const K_sets[6])[10] = { K_l015, K_l020, K_l025, K_l030, K_l035, K_l040 };
